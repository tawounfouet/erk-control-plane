import { describe, expect, it } from 'vitest'
import * as api from '@/lib/api/operations'

describe('operations API coverage', () => {
  it('covers category and operation type administration', async () => {
    expect((await api.listAllCategories()).count).toBe(1)
    expect((await api.listCategories())[0].code).toBe('PLUMBING')
    expect((await api.getCategoryOperationTypes('cat-001'))[0].code).toBe('LEAK')
    await expect(api.createCategory({ name: 'Électricité' } as never)).resolves.toMatchObject({ id: 'cat-new' })
    await expect(api.updateCategory('cat-001', { description: 'Mise à jour' })).resolves.toMatchObject({ description: 'Mise à jour' })
    await expect(api.deleteCategory('cat-001')).resolves.toBeUndefined()
    expect((await api.listOperationTypes()).count).toBe(1)
    expect(await api.getOperationTypesByCategory('cat-001')).toHaveLength(1)
    await expect(api.getOperationTypesRequiringApproval()).resolves.toEqual([])
    await expect(api.createOperationType({ name: 'Diagnostic' } as never)).resolves.toMatchObject({ id: 'type-new' })
  })

  it('covers the complete operation workflow and filters', async () => {
    expect((await api.listOperations()).count).toBe(4)
    expect((await api.getOperation('o-001')).operation_number).toBe('OP-2026-0001')
    await expect(api.createOperation({ title: 'Contrôle', operation_type: 'type-001' })).resolves.toMatchObject({ id: 'o-new' })
    await expect(api.updateOperation('o-001', { priority: 'HIGH' })).resolves.toMatchObject({ priority: 'HIGH' })
    await expect(api.getMyOperations()).resolves.not.toHaveLength(0)
    await expect(api.getMyRequests()).resolves.not.toHaveLength(0)
    await expect(api.getAssignedToMe()).resolves.not.toHaveLength(0)
    await expect(api.getPendingOperations()).resolves.not.toHaveLength(0)
    await expect(api.getInProgressOperations()).resolves.not.toHaveLength(0)
    await expect(api.getOverdueOperations()).resolves.not.toHaveLength(0)
    await expect(api.getHighPriorityOperations()).resolves.not.toHaveLength(0)
    await expect(api.assignOperation('o-001', 'u-staff')).resolves.toMatchObject({ assigned_to: 'u-staff' })
    await expect(api.startOperation('o-001')).resolves.toMatchObject({ status: 'IN_PROGRESS' })
    await expect(api.completeOperation('o-001', 'Terminé')).resolves.toMatchObject({ status: 'COMPLETED' })
    await expect(api.cancelOperation('o-001', 'Doublon')).resolves.toMatchObject({ status: 'CANCELLED' })
    await expect(api.changeOperationStatus('o-001', 'APPROVED')).resolves.toMatchObject({ status: 'APPROVED' })
    expect((await api.getOperationStats()).total).toBe(4)
    await expect(api.getOperationsByUnit('u-001')).resolves.not.toHaveLength(0)
    await expect(api.getOperationsByBuilding('b-001')).resolves.not.toHaveLength(0)
    await expect(api.getOperationsByResidence('r-001')).resolves.not.toHaveLength(0)
    await expect(api.deleteOperation('o-001')).resolves.toBeUndefined()
  })

  it('covers comments, notifications, attachments and history', async () => {
    expect((await api.listOperationComments()).count).toBe(1)
    await expect(api.createOperationComment({ operation: 'o-001', content: 'Note' })).resolves.toMatchObject({ id: 'comment-new' })
    await expect(api.getCommentsByOperation('o-001')).resolves.toHaveLength(1)
    await expect(api.getCommentReplies('comment-001')).resolves.toEqual([])
    expect((await api.listOperationNotifications()).count).toBe(1)
    await expect(api.getUnreadOperationNotifications()).resolves.toHaveLength(1)
    await expect(api.markOperationNotificationRead('notification-001')).resolves.toMatchObject({ is_read: true })
    await expect(api.markAllOperationNotificationsRead()).resolves.toHaveProperty('message')
    expect((await api.listOperationAttachments()).count).toBe(1)
    await expect(api.getOperationEvidencePhotos('o-001')).resolves.toHaveLength(1)
    await expect(api.uploadOperationAttachment('o-001', new File(['image'], 'photo.jpg', { type: 'image/jpeg' }))).resolves.toMatchObject({ id: 'attachment-new' })
    await expect(api.bulkUploadOperationAttachments('o-001', [new File(['a'], 'a.jpg')])).resolves.toHaveProperty('attachments')
    expect((await api.listOperationHistory()).count).toBe(1)
    await expect(api.getHistoryByOperation('o-001')).resolves.toHaveLength(1)
    await expect(api.getMyOperationActions()).resolves.toHaveLength(1)
  })
})
