import { describe, expect, it } from 'vitest'
import * as api from '@/lib/api/patrimoine'

describe('patrimoine control-plane API coverage', () => {
  it('covers unit types, buildings, floors and unit actions', async () => {
    expect((await api.listUnitTypes()).count).toBeGreaterThan(0)
    expect((await api.listCompositeUnitTypes())[0].is_composite).toBe(true)
    expect((await api.listRentableUnitTypes())[0].is_rentable).toBe(true)
    await expect(api.createUnitType({ name: 'Duplex', code: 'DUPLEX' })).resolves.toMatchObject({ id: 'ut-new' })
    await expect(api.updateUnitType('ut-001', { name: 'Studio premium' })).resolves.toMatchObject({ name: 'Studio premium' })
    await expect(api.deleteUnitType('ut-001')).resolves.toBeUndefined()

    expect((await api.listBuildings()).results).not.toHaveLength(0)
    expect((await api.getBuilding('b-001')).code).toBe('A')
    expect((await api.getBuildingStats('b-001')).total_units).toBe(12)
    await expect(api.createBuilding({ name: 'Résidence C', code: 'C' })).resolves.toMatchObject({ id: 'b-new' })
    await expect(api.updateBuilding('b-001', { name: 'Résidence rénovée' })).resolves.toMatchObject({ name: 'Résidence rénovée' })
    await expect(api.deleteBuilding('b-002')).resolves.toBeUndefined()
    expect((await api.getFloor('f-001')).units_count).toBe(4)
    await expect(api.createFloor({ building: 'b-001', name: 'Mezzanine' })).resolves.toMatchObject({ id: 'f-new' })
    await expect(api.updateFloor('f-001', { name: 'Rez-de-chaussée rénové' })).resolves.toMatchObject({ name: 'Rez-de-chaussée rénové' })
    await expect(api.deleteFloor('f-005')).resolves.toBeUndefined()
    await expect(api.createUnit({ identifier: 'A-NEW', name: 'Nouvelle unité' })).resolves.toMatchObject({ id: 'u-new' })
    await expect(api.updateUnit('u-002', { name: 'Studio A2 rénové' })).resolves.toMatchObject({ name: 'Studio A2 rénové' })
    await expect(api.changeUnitStatus('u-002', 'MAINTENANCE')).resolves.toMatchObject({ current_status: 'MAINTENANCE' })
    expect((await api.getUnitHierarchy('u-001')).path).toContain('A-001')
    await expect(api.getRentableUnits()).resolves.not.toHaveLength(0)
    await expect(api.getCompositeUnits()).resolves.toHaveLength(0)
    await expect(api.deleteUnit('u-005')).resolves.toBeUndefined()
  })

  it('covers features, history, room assets and legacy assignments', async () => {
    expect((await api.listUnitFeatures()).count).toBe(2)
    expect((await api.getUnitFeature('uf-001')).feature_name).toBe('Climatisation')
    await expect(api.createUnitFeature({ unit: 'u-001', feature_name: 'Balcon' })).resolves.toMatchObject({ id: 'uf-new' })
    await expect(api.updateUnitFeature('uf-001', { feature_value: 'false' })).resolves.toMatchObject({ feature_value: 'false' })
    await expect(api.deleteUnitFeature('uf-002')).resolves.toBeUndefined()
    expect((await api.listStatusHistory()).results[0].new_status).toBe('OCCUPIED')
    expect((await api.getStatusHistory('ush-001')).old_status).toBe('AVAILABLE')
    expect((await api.getStatusHistoryByUnit('u-001'))[0].unit).toBe('u-001')
    expect((await api.listRoomAssets({ managed_unit: 'u-001' })).count).toBe(2)
    expect((await api.getRoomAsset('ra-001')).code).toBe('WALL-01')
    expect((await api.getAssignment('ia-001')).unit).toBe('u-001')
    await expect(api.listAssignmentsNeedingMaintenance()).resolves.toEqual([])
    expect((await api.getInventoryItem('i-001')).reference).toBe('CLIM-9000')
    await expect(api.createInventoryItem({ name: 'Modèle test', category: 'OTHER' })).resolves.toMatchObject({ id: 'i-new' })
    await expect(api.updateInventoryItem('i-001', { notes: 'Catalogue vérifié' })).resolves.toMatchObject({ notes: 'Catalogue vérifié' })
    await expect(api.deleteInventoryItem('i-003')).resolves.toBeUndefined()
  })

  it('covers the complete intervention workflow', async () => {
    expect((await api.getInterventionStatistics()).total).toBe(1)
    expect((await api.listPendingInterventions())[0].status).toBe('PENDING')
    await expect(api.listInProgressInterventions()).resolves.toEqual([])
    await expect(api.listOverdueInterventions()).resolves.toEqual([])
    await expect(api.createIntervention({ unit: 'u-001', title: 'Test' })).resolves.toMatchObject({ id: 'pi-new' })
    await expect(api.getIntervention('pi-001')).resolves.toMatchObject({ id: 'pi-001' })
    await expect(api.updateIntervention('pi-001', { priority: 'URGENT' })).resolves.toMatchObject({ priority: 'URGENT' })
    await expect(api.startIntervention('pi-001')).resolves.toMatchObject({ status: 'IN_PROGRESS' })
    await expect(api.completeIntervention('pi-001', 'Résolu')).resolves.toMatchObject({ status: 'COMPLETED' })
    await expect(api.cancelIntervention('pi-001', 'Doublon')).resolves.toMatchObject({ status: 'CANCELLED' })
    await expect(api.deleteIntervention('pi-001')).resolves.toBeUndefined()
  })

  it('covers atomic equipment and micro-right actions', async () => {
    expect((await api.listEquipments()).count).toBe(2)
    expect((await api.listAvailableEquipments()).results[0].status).toBe('IN_STOCK')
    const created = await api.createEquipment({ template: 'i-003', designation: 'Ventilateur test' })
    expect(created.technical_reference).toBe('NEW-2026-00001')
    await expect(api.updateEquipment('eq-002', { notes: 'Inventorié' })).resolves.toMatchObject({ notes: 'Inventorié' })
    await expect(api.assignEquipment('eq-002', { managed_unit: 'u-002' })).resolves.toMatchObject({ status: 'ASSIGNED' })
    await expect(api.inspectEquipmentExit('eq-001', 'M')).resolves.toMatchObject({ condition: 'M' })
    await expect(api.unassignEquipment('eq-001', 'B')).resolves.toMatchObject({ status: 'IN_STOCK' })
    await expect(api.deleteEquipment('eq-002')).resolves.toBeUndefined()
  })

  it('covers protected invoice creation and audited voiding', async () => {
    expect((await api.listInvoices()).count).toBe(1)
    expect((await api.getInvoice('inv-001')).equipment_lines[0].technical_reference).toContain('VEN-')
    const invoice = await api.createInvoice({ invoice_number: 'FAC-NEW', supplier_name: 'Test', invoice_date: '2026-10-01', lines: [{ equipment: 'eq-002', unit_purchase_price: '45000' }] })
    expect(invoice.status).toBe('ACTIVE')
    await expect(api.voidInvoice('inv-001', 'Erreur fournisseur')).resolves.toMatchObject({ status: 'CANCELLED', void_reason: 'Erreur fournisseur' })
  })
})
